/* =========================================================================
   ВЫЕМКА БОЕВОГО ПРИЛОЖЕНИЯ ИЗ ПРОТОТИПА.

   Прототип — сцена: пульт, четыре устройства рядом, админка, магазин
   приложений, рабочий стол телефона, имитаторы оплаты и пушей, ревизор.
   Боевое приложение — один экран одного человека, без лесов.

   Границу провёл не я, а сам прототип (закон разделения демо/бой, 06.08.2026):
   лес несёт метку «ДЕМО» в шапке и data-scope="demo" в разметке, админка —
   data-scope="admin", список лесов лежит в SCAFFOLD_FNS. Здесь эти метки
   просто исполняются.

   ПОЧЕМУ СКРИПТОМ, А НЕ РУКАМИ: прототип живой и продолжает меняться. Копия,
   вырезанная руками, устареет к следующей сборке и начнёт врать. Скрипт
   переносит правку прототипа в боевое приложение одной командой.

   ПОЧЕМУ С ПРОВЕРКАМИ: каждая замена обязана совпасть ровно один раз. Если
   прототип изменился так, что кусок больше не найден, скрипт останавливается
   и называет место — вместо того чтобы молча собрать сломанное приложение.
   ========================================================================= */
import { copyFile, readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const SRC = path.join(ROOT, 'src', 'prototype.html');
const OUT_DIR = path.join(ROOT, 'www');
const OUT = path.join(OUT_DIR, 'index.html');

/* --------------------------------------------------------- режим сборки ---
   Без ключей собирается чистое боевое приложение. С --preview добавляется
   дверь для показа: мастер-код, сборка демо-мира и вход за роль — иначе
   приложение без сервера показать нечем, мир пустой и войти не за кого.

   Ключ --code=XXXX задаёт мастер-код. */
const ARGS = process.argv.slice(2);
const PREVIEW = ARGS.includes('--preview');
const CODE = (ARGS.find(a => a.startsWith('--code=')) || '--code=2026').slice(7);

/* Предпросмотр в релизе — это дверь без замка в приложении, которое стоит у
   людей на телефонах. Отказываемся вслух, а не молча собираем. */
if (PREVIEW && process.env.MYHOME_RELEASE === '1') {
  throw new Error('--preview и релизная сборка вместе не собираются: мастер-код в релиз не едет.');
}
if (PREVIEW && !/^\d{4,8}$/.test(CODE)) {
  throw new Error(`мастер-код «${CODE}» не годится: нужны 4–8 цифр.`);
}

let html = await readFile(SRC, 'utf8');
const before = html.length;
const done = [];

/* Замена, которая обязана сработать ровно один раз. */
function cut(what, from, to) {
  const n = html.split(from).length - 1;
  if (n !== 1) {
    throw new Error(`«${what}»: искомое место встречается ${n} раз(а), ожидался ровно один.\n` +
                    `Прототип изменился — поправьте выемку под новый текст.\n` +
                    `Искали:\n${from.slice(0, 300)}`);
  }
  html = html.replace(from, to);
  done.push(what);
}

/* Вырезать кусок от начала одного якоря до начала другого. Закрывающий якорь
   остаётся на месте; на месте вырезанного можно оставить замену. */
function cutRegion(what, openMark, closeMark, replacement = '') {
  const a = html.indexOf(openMark);
  const b = html.indexOf(closeMark, a);
  if (a < 0 || b < 0) throw new Error(`«${what}»: якоря не найдены (${a}, ${b}).`);
  html = html.slice(0, a) + replacement + html.slice(b);
  done.push(`${what} (вырезано ${b - a} символов)`);
}


/* Убрать объявление функции целиком.

   Считать фигурные скобки бесполезно: в коде живут регулярные выражения и
   деления, и счётчик на них сбивается — первая попытка выгрызла три мегабайта
   вместо ста килобайт. Опираемся на стиль самого файла: функция верхнего
   уровня начинается со слова function в первой колонке и заканчивается
   закрывающей скобкой тоже в первой колонке. Это правило файл держит везде. */
function dropFn(name) {
  const decl = '\nfunction ' + name + '(';
  const at = html.indexOf(decl);
  if (at < 0) return 0;                       /* нет такой — не наша забота */

  /* Конец объявления — последняя закрывающая скобка в первой колонке ПЕРЕД
     следующей функцией верхнего уровня. Просто «первая такая скобка» не годится:
     в пульте (ctrlHTML) шаблон разметки сам содержит скобку в первой колонке,
     и функция обрывалась на середине. */
  const nextFn = html.indexOf('\nfunction ', at + decl.length);
  const limit = nextFn < 0 ? html.length : nextFn;
  const end = html.lastIndexOf('\n}', limit);
  if (end < at) throw new Error(`лес «${name}»: не нашёлся конец объявления.`);
  const size = end + 2 - at;

  /* На месте леса остаётся пустышка, а не пустота. Причина живая: heatRec
     вешается слушателем на документ ОТДЕЛЬНОЙ строкой вне функции
     (document.addEventListener('click', heatRec, true)) — стоит убрать
     объявление совсем, и страница падает на этой строке ещё до первого экрана.
     Пустышка возвращает пустую строку: безвредна и как действие, и как кусок
     разметки, если её всё-таки кто-то позовёт. */
  html = html.slice(0, at) + '\n/* ДЕМО-лес «' + name + '» вынут при выемке боевой части */'
       + '\nfunction ' + name + '(){ return \'\'; }'
       + html.slice(end + 2);
  return size;
}

/* Разбирается ли ещё код страницы. Правило «скобка в первой колонке» верно
   почти везде, но не везде: в шаблоне разметки такая скобка тоже встречается.
   Поэтому каждое удаление проверяется на разбор, и неудачное откатывается —
   выемка не может собрать сломанное приложение, даже если ошиблась. */
function parses() {
  const a = html.indexOf('<script>') + 8;
  const b = html.indexOf('</script>', a);
  try { new Function(html.slice(a, b)); return true; }
  catch (e) { return false; }
}

/* Список лесов — из самого прототипа (SCAFFOLD_FNS), чтобы не расходиться. */
function scaffoldNames() {
  const m = html.match(/const SCAFFOLD_FNS = \[([\s\S]*?)\];/);
  if (!m) throw new Error('SCAFFOLD_FNS в прототипе не найден — список лесов взять неоткуда.');
  return [...m[1].matchAll(/'([A-Za-z_$][\w$]*)'/g)].map(x => x[1]);
}

/* ---------------------------------------------------------------- разметка */

/* Пульт сцены — вся полоса управления показом над телефонами. */
cutRegion('пульт сцены', '<div id="ctrl" data-scope="demo">', '<div class="stage" id="stage">');

/* Статическая сцена: четыре нарисованных телефона с магазинами и рабочими
   столами. Боевому приложению нужен один пустой корень — остальное соберёт
   render() при первом же проходе. */
cutRegion('статическая сцена', '<div class="stage" id="stage">', '<script>',
  '<div class="stage" id="stage"><div id="wrap-res"></div></div>\n');

/* ------------------------------------------------------------------ render */

/* Каркас сцены: было четыре контейнера, стал один. */
cut('каркас сцены',
  `    stage.innerHTML = '<div id="wrap-vaad"></div><div id="wrap-res"></div>'
      + '<div id="wrap-mas"></div><div id="wrap-admin"></div>';`,
  `    stage.innerHTML = '<div id="wrap-res"></div>';`);

/* Покраска: один телефон вместо трёх плюс админки. slot() отпадает вместе с
   подписью над телефоном — в бою над экраном не пишут, кто на нём сидит. */
cut('покраска сцены',
  `    paint('wrap-vaad',  slot('vaad', '1'), 'v:'+рольЭкр(D.vaad.screen)+':'+D.vaad.lang);
    paint('wrap-res',   slot('res',  '2'), 'r:'+рольЭкр(D.res.screen)+':'+D.res.lang);
    paint('wrap-mas',   slot('mas',  '3'), 'm:'+рольЭкр(D.mas.screen)+':'+D.mas.lang);
    paint('wrap-admin', adminHTML(), 'a');
    ['wrap-vaad','wrap-res','wrap-mas'].forEach(syncHatH);`,
  `    paint('wrap-res', phoneHTML(ДЕВ), 'r:'+рольЭкр(D[ДЕВ].screen)+':'+D[ДЕВ].lang);
    syncHatH('wrap-res');`);

/* Запасной путь render() — туда же. */
cut('запасной путь render',
  `    document.getElementById('stage') &&
      (document.getElementById('stage').innerHTML =
        slot('vaad','1')+slot('res','2')+slot('mas','3')+adminHTML());`,
  `    document.getElementById('stage') &&
      (document.getElementById('stage').innerHTML = phoneHTML(ДЕВ));`);

/* Пульт больше не собирается: его разметки в бою нет. */
cut('сборка пульта', '  const ctrlNew = ctrlHTML();', '  const ctrlNew = \'\';');

/* Боковая колонка дизайн-пульта — лес показа. */
cut('колонка дизайн-пульта', '  sideSync();   /* пульт дизайна — колонкой сбоку, телефоны остаются на виду */\n', '');

/* Ревизор обходит мир каждые 4 секунды — это наш инструмент стройки.
   В бою сторожить правила будет сервер, а не экран жильца. */
cut('ревизор в render', '  revQuick(); /* ревизор, фоновый слой (пакет 2): лёгкие проверки, не чаще раза в 4 сек */\n', '');

/* -------------------------------------------------------------- phoneHTML */

/* Корпус трубки: вырез камеры — часть рамки-декорации. */
cut('вырез камеры', '<div class="notch" data-scope="demo"></div>', '');

/* Нарисованный статусбар телефона — поверх настоящего рисовать нечего. */
cut('статусбар телефона', '      ${statusbarHTML()}\n', '');

/* Имитатор эквайринга: «страница платёжной компании» из демо. В бою человек
   уходит на настоящую хостинг-страницу провайдера. */
cut('имитатор оплаты', '      ${paySimHTML(dev)}\n', '');

/* Системная навигация телефона — тоже часть рамки. */
cut('навигация телефона',
  `  const homebar  = showHome ? sysnavHTML(dev, inApp) : '';`,
  `  const homebar  = '';`);

/* Магазин приложений и рабочий стол — декорация вокруг приложения.
   Боевое приложение уже установлено: человек открыл его с рабочего стола
   своего настоящего телефона. */
cut('магазин и рабочий стол',
  `    inner = (!st.installed || st.storeOpen !== false) ? storeHTML(dev) : springboardHTML(dev);`,
  `    inner = '';`);

/* ------------------------------------------------------------------- пуск */

/* Ревизор-по-таймеру снимается вместе с пультом; вместо него — вход в
   приложение. Состояние взято из demoInside(): «как в жизни после установки»,
   то есть экран входа и регистрации, без подсунутой готовой сессии. */
cut('пуск приложения',
  `revStartTimer();   /* Эдуард 04.08: ревизор смотрит мир каждые 4 секунды сам */`,
  `/* БОЕВОЙ ПУСК: приложение уже установлено, человек стоит на входе.
   Состояние — то же, что даёт demoInside() в прототипе: открыто, без заставки,
   без первого запуска, без сессии. Роль выберет сам экран входа. */
Object.assign(D[ДЕВ], { open:true, splash:false, installed:true, installing:false,
  storeOpen:false, onb:null, onbDone:true, userId:null, asRes:false, draft:{},
  tab:'home', screen:'fork' });
render();`);

/* Имя единственного устройства объявляем до первого использования: в бою
   телефон один, но код прототипа везде принимает его имя параметром, и ломать
   эту развязку ради одной строки незачем. */
cut('имя устройства', 'const D = {', 'const ДЕВ = \'res\';\nconst D = {');

/* ------------------------------------------------------------------- леса */

/* Теперь, когда никто из боевого кода их не зовёт, сами леса вынимаются.
   Список берётся из прототипа — прототип пополнил SCAFFOLD_FNS, выемка узнала.

   В предпросмотре леса остаются: показывать приложение не на чем, а собирает
   демо-мир как раз лес (makeEnv) и тянет за собой соседей. Разбирать, кто из
   них кому нужен, ради сборки для показа — работа впустую и лишний повод
   ошибиться; чистое боевое приложение собирается без ключа --preview и лесов
   в нём нет. */
if (PREVIEW) {
  done.push('леса: оставлены — предпросмотру нужен сборщик демо-мира');
} else {
  if (!parses()) throw new Error('код перестал разбираться ещё до выемки лесов — виновата правка выше.');
  let total = 0, gone = 0, missing = [], refused = [];
  for (const name of scaffoldNames()) {
    const snapshot = html;
    const n = dropFn(name);
    if (!n) { missing.push(name); continue; }
    if (parses()) { total += n; gone++; }
    else { html = snapshot; refused.push(name); }
  }
  done.push(`леса: вынуто ${gone} функций, ${(total / 1024).toFixed(0)} КБ`);
  if (missing.length) done.push(`  нет отдельным объявлением: ${missing.join(', ')}`);
  if (refused.length) done.push(`  оставлены (вырезать нечисто): ${refused.join(', ')}`);
}

/* --------------------------------------------------------------- раскладка */

cut('боевая раскладка', '</head>', '<link href="prod.css" rel="stylesheet">\n</head>');

/* Оболочка приложения — последней строкой, после всего кода прототипа:
   ей нужны уже объявленные D и navBack. В браузере она молчит. */
cut('оболочка приложения', '</body>',
    '<script src="app-shell.js"></script>\n</body>');

/* ---------------------------------------------------------- предпросмотр */

if (PREVIEW) {
  cut('дверь предпросмотра', '<script src="app-shell.js"></script>',
      '<script src="preview.js"></script>\n<script src="app-shell.js"></script>');
}

/* ------------------------------------------------------------------ вывод */

