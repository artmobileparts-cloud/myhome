import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const SRC = path.join(ROOT, 'src', 'prototype.html');
const OUT_DIR = path.join(ROOT, 'www');

let html = await readFile(SRC, 'utf8');
const done = [];

function cut(what, from, to) {
  const n = html.split(from).length - 1;
  if (n !== 1) {
    throw new Error(`«${what}»: место встречается ${n} раз(а), ожидался ровно один.\n` +
                    `Прототип изменился — поправьте сборку под новый текст.\n` +
                    `Искали:\n${from.slice(0, 300)}`);
  }
  html = html.replace(from, to);
  done.push(what);
}

/* --- 1. Режим настоящего телефона ---------------------------------------- */

cut('режим настоящего телефона',
  `  const real = q === '1' || (q !== '0' && авто);`,
  `  /* ⚠ ВНУТРИ ОБЁРТКИ СОМНЕНИЙ НЕТ (добавлено сборкой APK): определение по
     сенсорному узкому экрану верно для телефона, но мимо для планшета и
     складня. Приложение знает про себя, что оно приложение. */
  const вОбёртке = !!(window.Capacitor && window.Capacitor.isNativePlatform
                      && window.Capacitor.isNativePlatform());
  const real = q !== '0' && (q === '1' || авто || вОбёртке);`);

/* --- 2. Открываться приложением, а не страницей магазина ------------------ */

cut('пуск приложением',
  `applyLook();
revStartTimer();`,
  `applyLook();

/* ПУСК В ОБЁРТКЕ (добавлено сборкой APK): нарисованная страница магазина —
   часть пути «магазин → установка → первый запуск» и нужна на сцене. В APK
   человек уже установил приложение, и встречать его витриной Google Play
   внутри самого приложения незачем. Открываем там же, где он окажется в
   жизни сразу после установки: экран входа и регистрации, без подсунутой
   сессии — роль выберет сам экран. Состояние — то же, что даёт demoInside().
   Условие обязательно: в браузере на столе сцена должна остаться сценой. */
if(document.documentElement.classList.contains('real')){
  Object.assign(D.res, { open:true, splash:false, installed:true, installing:false,
    storeOpen:false, onb:null, onbDone:true, userId:null, asRes:false, draft:{},
    tab:'home', screen:'fork' });
}
revStartTimer();`);

/* --- оболочка ------------------------------------------------------------ */

/* Кнопка «Назад» и внешние ссылки. Подключается последней: ей нужны уже
   объявленные D и navBack. В браузере молчит. */
cut('оболочка приложения', '</body>', '<script src="app-shell.js"></script>\n</body>');

await mkdir(OUT_DIR, { recursive: true });
await writeFile(path.join(OUT_DIR, 'index.html'), html);

console.log('Сборка приложения из прототипа:');
for (const d of done) console.log('  · ' + d);
console.log(`Размер веб-части: ${(html.length / 1048576).toFixed(2)} МБ (знаков).`);
console.log('Облик, раскладка и гашение лесов — работа самого прототипа (html.real).');
